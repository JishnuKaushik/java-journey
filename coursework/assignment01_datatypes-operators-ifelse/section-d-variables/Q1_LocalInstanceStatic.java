/*
 * Q1. What is the difference between local, instance, and static variables
 * in Java?
 *
 * Ans: A local variable is declared inside a method/block, exists only
 * during that method's execution, and has no default value (must be
 * initialized before use). An instance variable is declared inside a class
 * but outside any method, belongs to each individual object, gets a default
 * value automatically, and lives as long as the object does. A static
 * variable is declared with the static keyword, belongs to the class itself
 * (shared across all objects), also gets a default value automatically, and
 * exists for the entire lifetime of the program.
 */
